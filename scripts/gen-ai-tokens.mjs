// Generates 400 single-use AI access tokens (256-bit / 64 hex chars).
//  - Writes api/lib/ai-tokens-allowed.php  (only SHA-256 hashes — safe to commit)
//  - Writes ai-access-tokens.txt           (plaintext list — DO NOT commit)
// Run: node scripts/gen-ai-tokens.mjs
import crypto from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COUNT = 400;

const tokens = [];
const hashes = [];
const seen = new Set();

while (tokens.length < COUNT) {
  const token = crypto.randomBytes(32).toString('hex'); // 256 bits, 64 hex chars
  if (seen.has(token)) continue;
  seen.add(token);
  tokens.push(token);
  hashes.push(crypto.createHash('sha256').update(token).digest('hex'));
}

const php = `<?php
declare(strict_types=1);

// AUTO-GENERATED by scripts/gen-ai-tokens.mjs — DO NOT EDIT BY HAND.
// SHA-256 hashes of the ${COUNT} single-use AI access tokens (256-bit each).
// Plaintext tokens are issued separately to the operator and are never stored here.

return [
${hashes.map((h) => `    '${h}',`).join('\n')}
];
`;

writeFileSync(resolve(ROOT, 'api/lib/ai-tokens-allowed.php'), php, 'utf8');
writeFileSync(resolve(ROOT, 'ai-access-tokens.txt'), tokens.join('\n') + '\n', 'utf8');

console.log(`Generated ${tokens.length} single-use tokens.`);
console.log('Wrote api/lib/ai-tokens-allowed.php (hashes) and ai-access-tokens.txt (plaintext).');
