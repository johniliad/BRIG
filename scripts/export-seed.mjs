// Generates:
//   - data/metric-library.json, data/relationships.json, data/story-rules.json
//   - database/seed.sql (categories, definitions, relationships, story rules,
//     provider config, methodology + settings) for phpMyAdmin import.
// Run: npm run export:seed
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const esc = (v) => {
  if (v === null || v === undefined) return 'NULL';
  return "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";
};
const jsonSql = (v) => esc(JSON.stringify(v));
const num = (v) => (v === null || v === undefined || Number.isNaN(v) ? 'NULL' : Number(v));

async function loadTs(entry) {
  const outfile = resolve(ROOT, '.tmp-seed', entry.replace(/[\\/]/g, '_') + '.mjs');
  mkdirSync(dirname(outfile), { recursive: true });
  await build({ entryPoints: [resolve(ROOT, entry)], bundle: true, format: 'esm', platform: 'node', outfile, logLevel: 'silent' });
  return import(pathToFileURL(outfile).href);
}

const libraryFile = JSON.parse(readFileSync(resolve(ROOT, 'src/data/metric-library.json'), 'utf8'));
const metrics = libraryFile.metrics;
const libraryVersion = libraryFile.library_version;

const libMod = await loadTs('src/data/library.ts');
const CATEGORIES = libMod.CATEGORIES;
const relMod = await loadTs('src/data/relationships.ts');
const RELATIONSHIP_RULES = relMod.RELATIONSHIP_RULES;
const storyMod = await loadTs('src/engine/storyline.ts');
const STORY_RULES = storyMod.STORY_RULES;

mkdirSync(resolve(ROOT, 'data'), { recursive: true });
writeFileSync(resolve(ROOT, 'data/metric-library.json'), JSON.stringify(libraryFile, null, 2) + '\n');
writeFileSync(
  resolve(ROOT, 'data/relationships.json'),
  JSON.stringify({ library_version: libraryVersion, relationship_rules: RELATIONSHIP_RULES }, null, 2) + '\n',
);
writeFileSync(
  resolve(ROOT, 'data/story-rules.json'),
  JSON.stringify({ library_version: libraryVersion, story_rules: STORY_RULES }, null, 2) + '\n',
);

const L = [];
L.push('-- AUTO-GENERATED by scripts/export-seed.mjs — do not edit by hand.');
L.push('-- Import into MySQL AFTER database/schema.sql.');
L.push('SET NAMES utf8mb4;');
L.push('');
L.push('DELETE FROM metric_definitions;');
L.push('DELETE FROM metric_categories;');
L.push('DELETE FROM metric_relationships;');
L.push('DELETE FROM metric_story_rules;');
L.push('DELETE FROM llm_provider_config;');
L.push('DELETE FROM methodology_versions;');
L.push('');

L.push('INSERT INTO metric_categories (category_key, label, letter, sort_order) VALUES');
L.push(CATEGORIES.map((c, i) => `(${esc(c.key)}, ${esc(c.label)}, ${esc(c.letter)}, ${i})`).join(',\n') + ';');
L.push('');

const defRows = metrics.map(
  (m) =>
    `(${esc(m.metric_key)}, ${esc(m.name)}, ${esc(m.category)}, ${esc(m.definition)}, ${esc(m.executive_meaning)}, ${esc(m.unit)}, ${esc(m.data_type)}, ${esc(m.directionality)}, ${num(m.board_relevance)}, ${num(m.trend_relevance)}, ${num(m.risk_relevance)}, ${jsonSql(m.recommended_visualizations)}, ${jsonSql(m.story_tags)}, ${jsonSql(m.related_metrics)}, ${jsonSql(m.caveats)}, ${esc(m.version)}, ${m.active ? 1 : 0})`,
);
L.push('INSERT INTO metric_definitions (metric_key, name, category_key, definition, executive_meaning, unit, data_type, directionality, board_relevance, trend_relevance, risk_relevance, visualization_json, story_tags_json, related_metric_keys_json, caveats_json, version, active) VALUES');
L.push(defRows.join(',\n') + ';');
L.push('');

const relRows = RELATIONSHIP_RULES.map(
  (r) =>
    `(${esc(r.rule_key)}, ${esc(r.metricA)}, ${esc(r.metricB)}, ${esc(r.type)}, ${esc(r.pattern)}, ${num(r.strength)}, ${esc(r.interpretation)}, ${esc(r.confidence)}, '1.0.0', 1)`,
);
L.push('INSERT INTO metric_relationships (rule_key, metric_a_key, metric_b_key, relationship_type, pattern, strength, interpretation, confidence_level, version, active) VALUES');
L.push(relRows.join(',\n') + ';');
L.push('');

const storyRows = STORY_RULES.map(
  (s) =>
    `(${esc(s.rule_key)}, ${esc(s.name)}, ${num(s.priority)}, ${esc(s.storyline_key)}, ${esc(s.storyline_title)}, ${esc(s.severity)}, ${jsonSql({ all: s.all ?? [], any: s.any ?? [] })}, ${jsonSql(s.variants ?? [s.storyline_title])}, ${jsonSql(s.preferredCharts)}, ${jsonSql([s.recommendedAction])}, ${jsonSql(s.counterSignals)}, '1.0.0', 1)`,
);
L.push('INSERT INTO metric_story_rules (rule_key, name, priority, storyline_key, storyline_title, severity, condition_json, message_templates_json, chart_recommendations_json, action_templates_json, counter_signals_json, version, active) VALUES');
L.push(storyRows.join(',\n') + ';');
L.push('');

L.push("INSERT INTO llm_provider_config (provider_key, provider_name, model_id, endpoint, enabled, active_for_public_demo, privacy_class, data_retention_summary, training_use_summary, provider_policy_url, current_limits_note, timeout_seconds, max_retries) VALUES");
L.push("('gemini', 'Google Gemini', 'gemini-1.5-flash', 'https://generativelanguage.googleapis.com/v1beta', 0, 0, 'third_party_training_use_possible', 'Free-tier content may be used to improve Google products.', 'Free-tier content may be used to improve products. Verify current terms.', 'https://ai.google.dev/gemini-api/docs/pricing', 'Limits and availability vary; verify current documentation.', 30, 2),");
L.push("('groq', 'Groq', 'llama-3.1-8b-instant', 'https://api.groq.com/openai/v1', 0, 0, 'third_party_no_training_claim', 'Inference data not retained by default (limited retention for reliability/abuse).', 'No training on customer data by default. Verify current terms.', 'https://console.groq.com/docs/your-data', 'Rate limits vary by model; verify current documentation.', 30, 2),");
L.push("('cohere', 'Cohere', 'command-r', 'https://api.cohere.com/v2', 0, 0, 'third_party_no_training_claim', 'Trial keys have usage limitations.', 'Verify current data-use terms.', 'https://docs.cohere.com/v1/docs/rate-limits', 'Trial keys limited; verify current documentation.', 30, 2),");
L.push("('openrouter', 'OpenRouter', 'openai/gpt-4o-mini', 'https://openrouter.ai/api/v1', 0, 0, 'third_party_routing_possible', 'Routing depends on the downstream model provider.', 'Depends on the downstream provider; verify current terms.', 'https://openrouter.ai/privacy', 'Rate limits depend on the selected model and account.', 30, 2);");
L.push('');

L.push('INSERT INTO methodology_versions (methodology_version, metric_library_version, rule_version, materiality_weights_json, changelog) VALUES');
L.push(`('1.0.0', ${esc(libraryVersion)}, '1.0.0', ${jsonSql({ board_relevance: 0.2, severity: 0.2, magnitude: 0.15, target_breach: 0.1, persistence: 0.1, relationship_strength: 0.1, business_impact: 0.1, regulatory_relevance: 0.05 })}, 'Initial release.');`);
L.push('');
L.push("INSERT INTO application_settings (setting_key, setting_value) VALUES ('public_demo_mode', 'true'), ('ai_enabled', 'false');");
L.push('');

writeFileSync(resolve(ROOT, 'database/seed.sql'), L.join('\n') + '\n');

console.log(`Metrics: ${metrics.length}`);
console.log(`Relationship rules: ${RELATIONSHIP_RULES.length}`);
console.log(`Story rules: ${STORY_RULES.length}`);
console.log('Wrote data/metric-library.json, data/relationships.json, data/story-rules.json, database/seed.sql');


