<?php
declare(strict_types=1);

/**
 * Server-side HTML template for the one-page Board report.
 * Generated from the SAME report model as the on-screen report. Returned as a
 * print-ready HTML fallback by the File_PDF PDF endpoint.
 */

function brig_pdf_e($v): string
{
    return htmlspecialchars((string) $v, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/** @param array<string,mixed> $m */
function brig_render_report_html(array $m): string
{
    $profile = $m['profile'] ?? [];
    $pos = $m['executivePosition'] ?? [];
    $conf = $m['confidence'] ?? [];
    $narr = $m['narrative'] ?? [];
    $findings = $m['findings'] ?? [];
    $charts = $m['charts'] ?? [];
    $meta = $m['metadata'] ?? [];

    $org = brig_pdf_e($profile['organisationLabel'] ?? 'Organisation');
    $period = brig_pdf_e(($profile['comparisonPeriod'] ?? '') . ' → ' . ($profile['reportingPeriod'] ?? ''));
    $audience = brig_pdf_e(str_replace('_', ' ', (string) ($profile['audience'] ?? 'general board')));
    $status = brig_pdf_e($pos['status'] ?? '');
    $confidence = brig_pdf_e($conf['boardNarrativeConfidence'] ?? '');
    $headline = brig_pdf_e($narr['headline'] ?? '');
    $message = brig_pdf_e($narr['executiveMessage'] ?? '');

    $findingsHtml = '';
    foreach (array_slice($findings, 0, 6) as $f) {
        $kind = ($f['kind'] ?? 'neutral') === 'positive' ? 'pos' : (($f['kind'] ?? '') === 'concern' ? 'con' : 'neu');
        $findingsHtml .= '<li class="' . $kind . '">' . brig_pdf_e($f['headline'] ?? '') . '</li>';
    }
    if ($findingsHtml === '') {
        $findingsHtml = '<li class="neu">No material changes were detected on the selected comparative metrics.</li>';
    }

    $list = static function ($items, string $empty) {
        $items = is_array($items) ? $items : [];
        if (count($items) === 0) {
            return '<li class="muted">' . brig_pdf_e($empty) . '</li>';
        }
        $out = '';
        foreach (array_slice($items, 0, 4) as $it) {
            $text = is_array($it) ? (($it['title'] ?? '') . (isset($it['rationale']) && $it['rationale'] ? ' — ' . $it['rationale'] : '')) : (string) $it;
            $out .= '<li>' . brig_pdf_e($text) . '</li>';
        }
        return $out;
    };

    $barHtml = '';
    $chart = $charts[0] ?? null;
    if (is_array($chart) && !empty($chart['data'])) {
        $data = $chart['data'];
        $max = 0.0001;
        foreach ($data as $d) $max = max($max, (float) ($d['value'] ?? 0));
        $barHtml .= '<div class="chart-title">' . brig_pdf_e($chart['title'] ?? '') . '</div>';
        $barHtml .= '<div class="chart-sub">' . brig_pdf_e($chart['subtitle'] ?? '') . '</div>';
        foreach ($data as $d) {
            $w = max(2, min(100, ((float) ($d['value'] ?? 0) / $max) * 100));
            $val = is_numeric($d['value'] ?? null) ? rtrim(rtrim(number_format((float) $d['value'], 1, '.', ','), '0'), '.') : '';
            $barHtml .= '<div class="bar-row"><span class="bar-label">' . brig_pdf_e($d['label'] ?? '') . '</span>'
                . '<span class="bar-track"><span class="bar-fill" style="width:' . $w . '%"></span></span>'
                . '<span class="bar-val">' . brig_pdf_e($val) . '</span></div>';
        }
    }

    $methodology = 'Methodology ' . brig_pdf_e($meta['methodology_version'] ?? '') . ' · Metric library '
        . brig_pdf_e($meta['metric_library_version'] ?? '') . ' · Rules ' . brig_pdf_e($meta['rule_version'] ?? '');
    $note = brig_pdf_e($narr['managementNote'] ?? '');

    // AI disclosure (only when the wording was AI-enhanced).
    $ai = is_array($m['ai'] ?? null) ? $m['ai'] : [];
    $aiNote = '';
    if (($ai['enabled'] ?? false) === true) {
        $p = trim((string) ($ai['provider'] ?? ''));
        $mo = trim((string) ($ai['model'] ?? ''));
        $aiNote = 'Executive wording enhanced using an external generative AI service'
            . ($p !== '' ? ' (' . brig_pdf_e($p) . ($mo !== '' ? ' · ' . brig_pdf_e($mo) : '') . ')' : '')
            . '; underlying calculations and analytical findings are generated by the application.';
    }

    $css = '@page{size:A4 landscape;margin:12mm}*{box-sizing:border-box}'
        . 'body{font-family:DejaVu Sans,Arial,sans-serif;color:#102a3a;font-size:11px;margin:0}'
        . '.head{display:flex;justify-content:space-between;border-bottom:3px solid #102a3a;padding-bottom:8px}'
        . '.brand{font-size:11px;font-weight:bold;color:#075e65;letter-spacing:.5px}'
        . '.org{font-size:15px;font-weight:bold;text-align:right}.dates{font-size:10px;color:#526675;text-align:right}'
        . '.status{margin:8px 0 4px}'
        . '.badge{display:inline-block;padding:3px 10px;border-radius:10px;font-weight:bold;font-size:10px;background:#e7f4f2;color:#075e65;border:1px solid #bfe0dd}'
        . '.badge.conf{background:#e6f5ec;color:#1b7a3d;border-color:#bfe3cd}'
        . 'h1{font-size:19px;margin:8px 0 6px}.msg{font-size:11.5px;color:#142b3b;margin:0 0 10px}'
        . '.section-title{font-size:10px;text-transform:uppercase;letter-spacing:.5px;color:#075e65;font-weight:bold;margin:10px 0 4px}'
        . 'ul{margin:0;padding-left:14px}li{margin-bottom:3px}'
        . '.con{color:#b32e2e}.pos{color:#1b7a3d}.neu{color:#526675}.muted{color:#7c8a99}'
        . '.cols{width:100%;border-collapse:collapse}.cols td{vertical-align:top;width:33%;padding-right:12px}'
        . '.chart-title{font-weight:bold;font-size:11px}.chart-sub{font-size:9px;color:#7c8a99;margin-bottom:4px}'
        . '.bar-row{display:flex;align-items:center;margin:3px 0}.bar-label{width:34%;font-size:9px;color:#526675}'
        . '.bar-track{flex:1;background:#eef2f7;height:9px;border-radius:4px;margin:0 6px}.bar-fill{display:block;height:9px;background:#075e65;border-radius:4px}'
        . '.bar-val{width:12%;text-align:right;font-size:9px;color:#102a3a}'
        . '.footer{border-top:1px solid #dce6e9;margin-top:10px;padding-top:6px;font-size:8.5px;color:#7c8a99}';

    return '<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Board cybersecurity summary</title>'
        . '<style>' . $css . '</style></head><body>'
        . '<div class="head"><div><div class="brand">CISO BOARD REPORTING INTELLIGENCE GENERATOR</div>'
        . '<div style="font-size:10px;color:#526675">Executive cybersecurity summary</div></div>'
        . '<div><div class="org">' . $org . '</div><div class="dates">' . $period . ' · ' . $audience . '</div></div></div>'
        . '<div class="status"><span class="badge">' . $status . '</span> <span class="badge conf">Board Narrative Confidence: ' . $confidence . '</span></div>'
        . '<h1>' . $headline . '</h1><p class="msg">' . $message . '</p>'
        . '<div class="section-title">Key signals</div><ul>' . $findingsHtml . '</ul>'
        . ($barHtml ? '<div class="section-title">Performance</div>' . $barHtml : '')
        . '<table class="cols"><tr>'
        . '<td><div class="section-title">Positive developments</div><ul>' . $list($narr['positiveDevelopments'] ?? [], 'None identified.') . '</ul></td>'
        . '<td><div class="section-title">Areas of concern</div><ul>' . $list($narr['keyRisks'] ?? [], 'None identified.') . '</ul></td>'
        . '<td><div class="section-title">Strategic priorities</div><ul>' . $list($narr['priorities'] ?? [], 'None identified.') . '</ul></td>'
        . '</tr></table>'
        . '<div class="section-title">Board attention / decision</div><ul>' . $list($narr['boardActions'] ?? [], 'No board action required.') . '</ul>'
        . '<div class="footer"><p>' . $note . '</p><p>' . $methodology . '</p>'
        . ($aiNote !== '' ? '<p>' . $aiNote . '</p>' : '')
        . '<p>CISO Board Reporting Intelligence Generator is an independently developed analytical and executive communication aid. It is not a cybersecurity audit, certification, legal or regulatory advice, or a substitute for professional judgement. Results depend on the quality of user-supplied data. Inferred relationships are analytical signals, not proof of causality.</p></div>'
        . '</body></html>';
}

