<?php
declare(strict_types=1);

require_once __DIR__ . '/bootstrap.php';

/**
 * Server-side PDF generation using File_PDF (an FPDF-style PHP class, e.g. the
 * PEAR File_PDF package). It is a programmatic PDF writer, not an HTML-to-PDF
 * renderer, so the report is drawn from the same report model.
 *
 * If File_PDF is not available, returns null and the caller falls back to the
 * print-ready HTML template. No browser automation is used.
 */

/** Convert UTF-8 to a Latin-1 (Windows-1252) string suitable for File_PDF core fonts. */
function brig_fp_text(string $s): string
{
    $map = ["\xE2\x80\x93" => '-', "\xE2\x80\x94" => '-', "\xE2\x86\x92" => '->', "\xE2\x80\xA6" => '...', "\xE2\x80\x99" => "'", "\xE2\x80\x9C" => '"', "\xE2\x80\x9D" => '"'];
    $s = strtr($s, $map);
    if (function_exists('iconv')) {
        $c = @iconv('UTF-8', 'Windows-1252//TRANSLIT', $s);
        if ($c !== false) {
            $s = $c;
        }
    }
    $clean = preg_replace('/[^\x09\x0A\x0D\x20-\xFF]/', '', $s);
    return $clean ?? '';
}

function brig_load_file_pdf(): bool
{
    if (class_exists('File_PDF')) {
        return true;
    }
    $cfg = brig_config()['pdf'] ?? [];
    $path = $cfg['file_pdf_path'] ?? null;
    $candidates = [];
    if (is_string($path) && $path !== '') {
        $candidates[] = $path;
    }
    $candidates[] = dirname(__DIR__, 2) . '/vendor/File/PDF.php';
    $candidates[] = dirname(__DIR__) . '/vendor/File/PDF.php';
    $candidates[] = dirname(__DIR__, 2) . '/File_PDF.php';
    foreach ($candidates as $c) {
        if ($c && is_file($c)) {
            require_once $c;
            break;
        }
    }
    if (!class_exists('File_PDF') && function_exists('stream_resolve_include_path')) {
        $inc = stream_resolve_include_path('File/PDF.php');
        if ($inc) {
            require_once 'File/PDF.php';
        }
    }
    return class_exists('File_PDF');
}

/**
 * Render the report to PDF bytes using File_PDF, or null if File_PDF is absent
 * or rendering fails (caller then serves the printable HTML fallback).
 *
 * @param array<string,mixed> $m
 */
function brig_render_report_pdf_filepdf(array $m): ?string
{
    if (!brig_load_file_pdf()) {
        return null;
    }

    $profile = $m['profile'] ?? [];
    $pos = $m['executivePosition'] ?? [];
    $conf = $m['confidence'] ?? [];
    $narr = $m['narrative'] ?? [];
    $findings = is_array($m['findings'] ?? null) ? $m['findings'] : [];
    $charts = is_array($m['charts'] ?? null) ? $m['charts'] : [];
    $meta = $m['metadata'] ?? [];

    $ai = is_array($m['ai'] ?? null) ? $m['ai'] : [];
    $aiNote = '';
    if (($ai['enabled'] ?? false) === true) {
        $p = trim((string) ($ai['provider'] ?? ''));
        $mo = trim((string) ($ai['model'] ?? ''));
        $aiNote = brig_fp_text(
            'Executive wording enhanced using an external generative AI service'
            . ($p !== '' ? ' (' . $p . ($mo !== '' ? ' / ' . $mo : '') . ')' : '')
            . '; underlying calculations and analytical findings are generated by the application.'
        );
    }

    $org = brig_fp_text((string) ($profile['organisationLabel'] ?? 'Organisation'));
    $period = brig_fp_text(($profile['comparisonPeriod'] ?? '') . ' -> ' . ($profile['reportingPeriod'] ?? ''));
    $audience = brig_fp_text(str_replace('_', ' ', (string) ($profile['audience'] ?? 'general board')));
    $status = brig_fp_text((string) ($pos['status'] ?? ''));
    $confidence = brig_fp_text((string) ($conf['boardNarrativeConfidence'] ?? ''));
    $headline = brig_fp_text((string) ($narr['headline'] ?? ''));
    $message = brig_fp_text((string) ($narr['executiveMessage'] ?? ''));

    try {
        $pdf = new File_PDF('L', 'mm', 'A4');
        if (method_exists($pdf, 'SetMargins')) {
            $pdf->SetMargins(12, 12, 12);
        }
        if (method_exists($pdf, 'SetAutoPageBreak')) {
            $pdf->SetAutoPageBreak(true, 10);
        }
        $pdf->AddPage('L');

        $W = 273.0;
        $x = 12.0;
        $yTop = 12.0;

        $section = function (string $title) use ($pdf, $x): void {
            $pdf->SetFont('Arial', 'B', 8);
            $pdf->SetTextColor(7, 94, 101);
            $pdf->SetXY($x, $pdf->GetY());
            $pdf->Cell(0, 5, strtoupper(brig_fp_text($title)), 0, 1);
            $pdf->SetTextColor(16, 42, 58);
        };
        $bullets = function (array $items, string $empty) use ($pdf, $x, $W): void {
            $pdf->SetFont('Arial', '', 9);
            $pdf->SetTextColor(20, 43, 59);
            $list = array_slice($items, 0, 6);
            if (count($list) === 0) {
                $pdf->SetX($x);
                $pdf->MultiCell($W, 4.5, brig_fp_text($empty), 0, 1);
            }
            foreach ($list as $it) {
                $t = is_array($it) ? (($it['title'] ?? '') . (!empty($it['rationale']) ? ' - ' . $it['rationale'] : '')) : (string) $it;
                $pdf->SetX($x);
                $pdf->MultiCell($W, 4.5, brig_fp_text('- ' . $t), 0, 1);
            }
            $pdf->SetTextColor(16, 42, 58);
            $pdf->Ln(1);
        };

        // Header
        $pdf->SetFont('Arial', 'B', 9);
        $pdf->SetTextColor(7, 94, 101);
        $pdf->SetXY($x, $yTop);
        $pdf->Cell(160, 5, 'CISO BOARD REPORTING INTELLIGENCE GENERATOR', 0, 0);
        $pdf->SetFont('Arial', 'B', 12);
        $pdf->SetTextColor(16, 42, 58);
        $pdf->Cell(113, 5, $org, 0, 1, 'R');
        $pdf->SetFont('Arial', '', 9);
        $pdf->SetTextColor(82, 102, 117);
        $pdf->SetX($x);
        $pdf->Cell(160, 4.5, 'Executive cybersecurity summary', 0, 0);
        $pdf->Cell(113, 4.5, $period . '  |  ' . $audience, 0, 1, 'R');

        $pdf->SetDrawColor(16, 42, 58);
        $pdf->SetLineWidth(0.6);
        $yy = $pdf->GetY() + 1;
        $pdf->Line($x, $yy, $x + $W, $yy);
        $pdf->Ln(3);

        // Status
        $pdf->SetFont('Arial', 'B', 10);
        $pdf->SetTextColor(7, 94, 101);
        $pdf->SetX($x);
        $pdf->Cell(0, 6, 'Status: ' . $status . '     Board Narrative Confidence: ' . $confidence, 0, 1);
        $pdf->SetTextColor(16, 42, 58);

        // Headline + message
        $pdf->SetFont('Arial', 'B', 15);
        $pdf->SetX($x);
        $pdf->MultiCell($W, 7, $headline, 0, 1);
        $pdf->SetFont('Arial', '', 9.5);
        $pdf->SetTextColor(20, 43, 59);
        $pdf->SetX($x);
        $pdf->MultiCell($W, 4.6, $message, 0, 1);
        $pdf->SetTextColor(16, 42, 58);
        $pdf->Ln(1);

        // Key signals
        $section('Key signals');
        $findingTexts = [];
        foreach (array_slice($findings, 0, 6) as $f) {
            $findingTexts[] = (string) ($f['headline'] ?? '');
        }
        $bullets($findingTexts, 'No material changes were detected on the selected comparative metrics.');

        // Performance bars (from the first deterministic chart)
        $chart = $charts[0] ?? null;
        if (is_array($chart) && !empty($chart['data'])) {
            $section($chart['title'] ?? 'Performance');
            $pdf->SetFont('Arial', '', 8);
            $pdf->SetTextColor(82, 102, 117);
            $pdf->SetX($x);
            $pdf->Cell(0, 4, brig_fp_text((string) ($chart['subtitle'] ?? '')), 0, 1);
            $pdf->SetTextColor(16, 42, 58);
            $data = array_slice($chart['data'], 0, 8);
            $max = 0.0001;
            foreach ($data as $d) {
                $max = max($max, (float) ($d['value'] ?? 0));
            }
            $labelW = 80.0;
            $barX = $x + $labelW;
            $barW = 150.0;
            $valW = $W - $labelW - $barW - 2;
            foreach ($data as $d) {
                $rowY = $pdf->GetY();
                $pdf->SetFont('Arial', '', 8);
                $pdf->SetTextColor(82, 102, 117);
                $pdf->SetXY($x, $rowY);
                $pdf->Cell($labelW, 5, brig_fp_text(substr((string) ($d['label'] ?? ''), 0, 44)), 0, 0);
                $pdf->SetFillColor(243, 247, 248);
                $pdf->Rect($barX, $rowY + 0.9, $barW, 3.4, 'F');
                $w = $barW * ((float) ($d['value'] ?? 0) / $max);
                if ($w < 1) {
                    $w = 1;
                }
                $pdf->SetFillColor(7, 94, 101);
                $pdf->Rect($barX, $rowY + 0.9, $w, 3.4, 'F');
                $pdf->SetTextColor(16, 42, 58);
                $pdf->SetXY($barX + $barW + 2, $rowY);
                $pdf->Cell($valW, 5, is_numeric($d['value'] ?? null) ? (string) round((float) $d['value'], 1) : '', 0, 1);
            }
            $pdf->Ln(1);
        }

        // Narrative sections
        $section('Positive developments');
        $bullets($narr['positiveDevelopments'] ?? [], 'None identified.');
        $section('Areas of concern');
        $bullets($narr['keyRisks'] ?? [], 'None identified.');
        $section('Strategic priorities');
        $bullets($narr['priorities'] ?? [], 'None identified.');
        $section('Board attention / decision');
        $bullets($narr['boardActions'] ?? [], 'No board action required.');

        // Footer
        $pdf->SetTextColor(82, 102, 117);
        $pdf->SetFont('Arial', '', 7.5);
        $pdf->SetX($x);
        $pdf->MultiCell($W, 3.6, brig_fp_text((string) ($narr['managementNote'] ?? '')), 0, 1);
        $pdf->SetX($x);
        $pdf->MultiCell($W, 3.6, 'Methodology ' . ($meta['methodology_version'] ?? '') . '  |  Metric library ' . ($meta['metric_library_version'] ?? '') . '  |  Rules ' . ($meta['rule_version'] ?? ''), 0, 1);
        if ($aiNote !== '') {
            $pdf->SetX($x);
            $pdf->MultiCell($W, 3.6, $aiNote, 0, 1);
        }
        $pdf->SetX($x);
        $pdf->MultiCell($W, 3.6, 'Independently developed analytical and executive communication aid. Not an audit, certification, legal or regulatory advice, or a substitute for professional judgement. Results depend on data quality. Relationships are analytical signals, not proof of causality.', 0, 1);

        // Obtain PDF bytes (dest 'S' returns the document; otherwise capture echo).
        $capture = static function (callable $fn): ?string {
            ob_start();
            $ret = null;
            try {
                $ret = $fn();
            } catch (\Throwable $e) {
                $ret = null;
            }
            $echo = ob_get_clean();
            if (is_string($ret) && strpos($ret, '%PDF') !== false) {
                return $ret;
            }
            if (is_string($echo) && strpos($echo, '%PDF') !== false) {
                return $echo;
            }
            if (is_string($ret) && strlen($ret) > 4) {
                return $ret;
            }
            if (is_string($echo) && strlen($echo) > 4) {
                return $echo;
            }
            return null;
        };

        $bytes = $capture(static fn() => $pdf->Output('S'));
        if ($bytes === null) {
            $bytes = $capture(static fn() => $pdf->Output());
        }
        return $bytes;
    } catch (\Throwable $e) {
        error_log('[BRIG] File_PDF render failed: ' . $e->getMessage());
        return null;
    }
}

